"""Macros for the indexed-rebuild study (protocol.json).

Writes paper/tables/indexed_numbers.tex and results/summary.csv.
"""
import csv
import json
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
RES = HERE / "results"
MT = ROOT / "experiments" / "minimal_touch" / "results"
OUT = ROOT / "paper" / "tables" / "indexed_numbers.tex"
INDEX = ["kd_enemy", "ball_enemy", "kd_class", "ball_class"]
RUNS = {"Cora": ("cora", [0]), "CiteSeer": ("citeseer", [0]), "Ogb": ("ogbn-arxiv", [0, 1, 2])}


def comma(x):
    return f"{x:,.0f}".replace(",", "{,}")


def rec(ds, seed, v):
    r = json.loads((RES / f"{ds}_seed{seed}_{v}.json").read_text())
    assert r.get("exact") is True, (ds, seed, v)
    return r


rows, macros = [], {}
for tag, (ds, seeds) in RUNS.items():
    gram, best, ratio = [], [], []
    for s in seeds:
        g = rec(ds, s, "gram")["median_s"]
        idx = {v: rec(ds, s, v)["median_s"] for v in INDEX}
        v_best = min(idx, key=idx.get)
        gram.append(g)
        best.append(idx[v_best])
        ratio.append(idx[v_best] / g)
        rows.append([ds, s, g] + [idx[v] for v in INDEX] + [v_best, idx[v_best] / g])
    gram, best, ratio = map(np.array, (gram, best, ratio))
    if tag == "Ogb":
        macros.update(IdxOgbGramS=f"{gram.mean():.1f}", IdxOgbIndexS=f"{best.mean():.0f}")
        # speedup of an arrival over the fastest indexed rebuild (radii + vectorized weights)
        sp = []
        for s, b in zip(seeds, best):
            d = json.loads((MT / "ogb_minimal" / f"seed_{s}.json").read_text())
            lat = np.mean([x["total_ms"] for x in d["per_insertion_records"]])
            sp.append((b + d["batch_anchors"][-1]["batch_w_s"]) * 1000 / lat)
        macros["IdxOgbSpeedupVsIndex"] = comma(np.mean(sp))
    else:
        macros.update({f"Idx{tag}GramMs": f"{gram[0] * 1000:.0f}", f"Idx{tag}IndexS": f"{best[0]:.2f}"})
    macros[f"Idx{tag}Slowdown"] = f"{ratio.mean():.0f}"

all_ratios = [r[-1] for r in rows]
macros["IdxSlowdownMin"] = f"{min(all_ratios):.0f}"
macros["IdxSlowdownMax"] = f"{max(all_ratios):.0f}"

with open(RES / "summary.csv", "w", newline="") as f:
    w = csv.writer(f)
    w.writerow(["dataset", "seed", "gram_s"] + [f"{v}_s" for v in INDEX] + ["fastest_index", "fastest_index_over_gram"])
    w.writerows(rows)

lines = ["% Auto-generated by experiments/indexed_rebuild/summarize.py -- do not edit by hand",
         "% Source: experiments/indexed_rebuild/results/"]
lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in macros.items()]
OUT.write_text("\n".join(lines) + "\n")
print("\n".join(lines))
