"""
Generate two manuscript tables from the experiment artifacts (no hand-typed
numbers):

  docs/manuscript/tables/tab_datasets.tex        -- dataset descriptors
  docs/manuscript/tables/tab_scale_breakdown.tex -- per-dataset parameters that
      drive the |V|-scaling speedup (|V|, |B|, mean |T_adj|, and the four
      timing components), i.e. the tabular form of Figure fig:scale-speedup.

Run: python3 experiments/build_dataset_tables.py
"""
import json
import os

HERE = os.path.dirname(__file__)
TAB = os.path.join(HERE, "..", "docs", "manuscript", "tables")
SCALE = json.load(open(os.path.join(HERE, "results", "e2e_scale_timing_results.json")))["results"]
OGB = json.load(open(os.path.join(HERE, "results", "e2e_ogb_stream_results.json")))
SCALE = {r["graph"]: r for r in SCALE}

# static descriptors (|V|, |B|, classes, undirected edges, source, role)
DATASETS = [
    ("Cora",       2708,   1433, 7,  "5{,}278",     "Planetoid public split~\\cite{fey2019fast}", "RQ1--RQ3"),
    ("CiteSeer",   3327,   3703, 6,  "4{,}552",     "Planetoid public split~\\cite{fey2019fast}", "RQ1--RQ3"),
    ("PubMed",     19717,  500,  3,  "44{,}324",    "Planetoid public split~\\cite{fey2019fast}", "RQ2 (scaling)"),
    ("SBM-2k",      2000,   50,   None, "$\\bar d \\approx 10$", "Synthetic Gaussian",   "RQ1 (locality)"),
    ("SBM sweep", None, 100, 5, "$\\bar d \\approx 10$", "Synthetic Gaussian",     "RQ2 (scaling)"),
    ("ogbn-arxiv", 169343, 128,  40, "1{,}157{,}799", "OGB~\\cite{hu2020ogb}",                   "RQ1--RQ2"),
]


def datasets_table():
    rows = []
    for name, V, B, C, E, src, role in DATASETS:
        Vs = r"\makecell{6k, 12k\\25k}" if V is None else f"{V:,}".replace(",", "{,}")
        Cs = "---" if C is None else str(C)
        rows.append(f"    {name} & {Vs} & {B} & {Cs} & {E} & {src} & {role} \\\\")
    body = "\n".join(rows)
    return f"""% Auto-generated by experiments/build_dataset_tables.py -- do not edit by hand
\\begin{{table*}}[pos=!htbp]
  \\centering
  \\small
  \\caption{{Experimental graphs. $|V|$: nodes; $|B|$: feature dimension; edges are undirected. Cora, CiteSeer and PubMed use the standard Planetoid public split. SBM graphs are synthetic (Gaussian class-conditional features, mean degree $\\bar d \\approx 10$): the 6k/12k/25k sweep has 5 balanced classes and full $|B|=100$; SBM-2k is a smaller graph ($|B|=50$ top-variance) used only for the $\\delta$ affected-fraction check (Table~\\ref{{tab:locality}}). ogbn-arxiv supports scaling and checkpoint correctness (Figure~\\ref{{fig:scale-speedup}} and Section~\\ref{{sec:correctness-locality}}).}}
  \\label{{tab:datasets}}
  \\begin{{tabularx}}{{\\linewidth}}{{l*{{4}}{{>{{\\centering\\arraybackslash}}X}}ll}}
    \\toprule
    Graph & $|V|$ & $|B|$ & Classes & Edges & Source & Used in \\\\
    \\midrule
{body}
    \\bottomrule
  \\end{{tabularx}}
\\end{{table*}}
"""


def _num(x, digits):
    """LaTeX number with {,} thousands sep, `digits` decimals."""
    s = f"{x:,.{digits}f}"
    return s.replace(",", "{,}")


def _ms(x):
    return _num(x, 2) if x < 10 else (_num(x, 1) if x < 1000 else _num(x, 0))


def breakdown_table():
    order = [("cora", "Cora"), ("citeseer", "CiteSeer"), ("SBM-6000", "SBM-6k"),
             ("SBM-12000", "SBM-12k"), ("pubmed", "PubMed"), ("SBM-25000", "SBM-25k")]
    rows = []
    for key, label in order:
        r = SCALE[key]
        V = _num(r["n_active_start"], 0)
        B = {"cora": 1433, "citeseer": 3703, "pubmed": 500}.get(key, 100)
        tadj = f"{r['touch_mean']:.1f}" if "touch_mean" in r else "n/a"
        rows.append(
            f"    {label} & {V} & {B} & {tadj}"
            f" & {_ms(r['inc_delta_ms'])} & {_ms(r['inc_w_ms'])}"
            f" & {_ms(r['batch_delta_vec_ms'])} & {_ms(r['batch_w_vec_ms'])}"
            f" & {r['speedup_end_to_end_fair']:.0f} $\\pm$ {r.get('speedup_std', 0.0):.0f}$\\times$ \\\\"
        )
    o = OGB
    pi = o["per_insertion_ms"]
    anchor = o["batch_anchors"][-1]
    rows.append(
        f"    ogbn-arxiv\\tnote{{a}} & {_num(anchor['n_active'], 0)} & 128 & {o['touch']['t_adj_mean']:.1f}"
        f" & {_ms(pi['delta_mean'])} & {_ms(pi['w_mean'])}"
        f" & {_ms(anchor['batch_delta_s']*1000)} & {_ms(anchor['batch_w_s']*1000)}"
        f" & {_num(o['speedup_end_to_end_stateful'], 0)}$\\times$ \\\\"
    )
    body = "\n".join(rows)
    anchor_list = ", ".join(f"${a['batch_total_s']:.1f}$" for a in o["batch_anchors"])
    recs = o["per_insertion_records"]
    n_first = _num(o["n_init"], 0)   # active count BEFORE the first insertion
    n_last = _num(recs[-1]["n_active"], 0)
    n_dataset = _num(o["n_total"], 0)
    n_rest = o["n_total"] - o["n_init"]      # nodes left to stream in
    n_stream = _num(n_rest, 0)
    proj_min = n_rest * pi["total_mean"] / 1000.0 / 60.0
    proj_days = n_rest * anchor["batch_total_s"] / 86400.0
    return f"""% Auto-generated by experiments/build_dataset_tables.py -- do not edit by hand
\\begin{{table*}}[pos=!htbp]
\\begin{{threeparttable}}
  \\centering
  \\small
  \\caption{{Per-graph maintenance costs and speedups corresponding to Figure~\\ref{{fig:scale-speedup}}. $|V|$ is the active node count, $|B|$ the feature dimension, and $|\\mathcal{{T}}_{{adj}}|$ the mean touch-set size; timing columns are in milliseconds.}}
  \\label{{tab:scale-breakdown}}
  \\begin{{tabularx}}{{\\linewidth}}{{l*{{8}}{{>{{\\centering\\arraybackslash}}X}}}}
    \\toprule
    Graph & $|V|$ & $|B|$ & $|\\mathcal{{T}}_{{adj}}|$ & Inc.\\ $\\delta$ & Inc.\\ $W$ & Batch $\\delta$ & Batch $W$ & Speedup \\\\
          &       &       &        & (ms) & (ms) & (ms) & (ms) & \\\\
    \\midrule
{body}
    \\bottomrule
  \\end{{tabularx}}
  \\begin{{tablenotes}}[flushleft]
  \\footnotesize
  \\item For citation and SBM graphs, timings average eight insertions within each of three seeds, then average across seeds. Speedups average per-step ratios within each seed; the reported mean and population SD are across seeds. Timing columns do not report SD.
  \\item[a] One stateful stream of 200 insertions, from ${n_first}$ to ${n_last}$ active nodes. Incremental columns are per-step means; batch columns are the final rebuild. Speedup divides the final batch anchor by mean incremental total, including bookkeeping; no seed-level SD is available. Full-state correctness is checked at three anchors. See Section~\\ref{{sec:experiments}} for protocol, memory use and full-stream projections.
  \\end{{tablenotes}}
\\end{{threeparttable}}
\\end{{table*}}
"""


def main():
    open(os.path.join(TAB, "tab_datasets.tex"), "w").write(datasets_table())
    open(os.path.join(TAB, "tab_scale_breakdown.tex"), "w").write(breakdown_table())
    print("[PASS] wrote tab_datasets.tex and tab_scale_breakdown.tex")


if __name__ == "__main__":
    main()
